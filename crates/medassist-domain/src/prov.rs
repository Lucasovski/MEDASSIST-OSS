//! Provenance tracking. Every clinical datum records *where it came from* so
//! that AI inferences, imported documents and professional decisions are never
//! conflated. This is a core safety property of MedAssist OSS.

use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// The epistemic status / origin class of a piece of clinical content.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ProvenanceKind {
    /// Typed or confirmed directly by a healthcare professional.
    ProfessionalEntry,
    /// Reported by the patient (subjective account).
    PatientReport,
    /// Measured objective data (e.g. vital signs from a device).
    ObjectiveMeasurement,
    /// Extracted from an imported document/lab report (not yet reviewed).
    ImportedDocument,
    /// Produced by a transcription engine from audio (not yet reviewed).
    Transcription,
    /// Generated by an AI model as a suggestion (never a final record).
    AiSuggestion,
}

impl ProvenanceKind {
    pub fn as_str(&self) -> &'static str {
        match self {
            ProvenanceKind::ProfessionalEntry => "professional_entry",
            ProvenanceKind::PatientReport => "patient_report",
            ProvenanceKind::ObjectiveMeasurement => "objective_measurement",
            ProvenanceKind::ImportedDocument => "imported_document",
            ProvenanceKind::Transcription => "transcription",
            ProvenanceKind::AiSuggestion => "ai_suggestion",
        }
    }

    /// Whether content of this kind may be treated as a confirmed clinical
    /// fact without further human review. Only professional entries and
    /// confirmed objective measurements qualify.
    pub fn is_confirmed_fact(&self) -> bool {
        matches!(
            self,
            ProvenanceKind::ProfessionalEntry | ProvenanceKind::ObjectiveMeasurement
        )
    }

    pub fn requires_review(&self) -> bool {
        !self.is_confirmed_fact()
    }
}

/// Reference to the concrete artifact a piece of content was derived from.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SourceRef {
    /// An uploaded document (PDF/lab/etc.), optionally with a page/offset.
    Document { id: Uuid, locator: Option<String> },
    /// A transcription, optionally a time range within it.
    Transcription { id: Uuid, start_ms: Option<u64>, end_ms: Option<u64> },
    /// An AI job that produced a draft.
    AiJob { id: Uuid, model: Option<String> },
    /// Entered live by a practitioner session.
    Practitioner { user_id: Uuid },
    /// Imported from an external system (e.g. HL7 message id).
    External { system: String, identifier: String },
}

/// Full provenance record attached to clinical content.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Provenance {
    pub kind: ProvenanceKind,
    pub source: SourceRef,
}

impl Provenance {
    pub fn new(kind: ProvenanceKind, source: SourceRef) -> Self {
        Self { kind, source }
    }

    pub fn professional(user_id: Uuid) -> Self {
        Self::new(
            ProvenanceKind::ProfessionalEntry,
            SourceRef::Practitioner { user_id },
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ai_suggestions_are_never_confirmed_facts() {
        assert!(ProvenanceKind::AiSuggestion.requires_review());
        assert!(!ProvenanceKind::AiSuggestion.is_confirmed_fact());
        assert!(!ProvenanceKind::Transcription.is_confirmed_fact());
        assert!(!ProvenanceKind::ImportedDocument.is_confirmed_fact());
        assert!(ProvenanceKind::ProfessionalEntry.is_confirmed_fact());
    }

    #[test]
    fn provenance_roundtrips_json() {
        let p = Provenance::new(
            ProvenanceKind::Transcription,
            SourceRef::Transcription { id: Uuid::new_v4(), start_ms: Some(0), end_ms: Some(1500) },
        );
        let s = serde_json::to_string(&p).unwrap();
        let back: Provenance = serde_json::from_str(&s).unwrap();
        assert_eq!(p, back);
    }
}
